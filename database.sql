CREATE TABLE administrador (
    id_administrador INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(15)  NOT NULL,
    apellido   VARCHAR(15)  NOT NULL,
    "contraseña" VARCHAR(200) NOT NULL,
    telefono   VARCHAR(15)  NOT NULL,
    correo     VARCHAR(30)  NOT NULL,
    documento  VARCHAR(20)  NOT NULL,
    CONSTRAINT documento_admin_uq UNIQUE (documento),
    CONSTRAINT correo_admin_uq UNIQUE (correo)
);

CREATE TABLE cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(15)  NOT NULL,
    apellido   VARCHAR(15)  NOT NULL,
    "contraseña" VARCHAR(200) NOT NULL,
    telefono   VARCHAR(15)  NOT NULL,
    correo     VARCHAR(200) NOT NULL,
    documento  VARCHAR(20)  NOT NULL,
    CONSTRAINT correo_cliente_uq UNIQUE (correo),
    CONSTRAINT documento_cliente_uq UNIQUE (documento)
);

CREATE TABLE sede (
    id_sede   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(30) NOT NULL,
    ciudad    VARCHAR(15) NOT NULL,
    telefono  VARCHAR(15) NOT NULL,
    direccion VARCHAR(50) NOT NULL,
    imagen    VARCHAR(200)
);

CREATE TABLE imagen_sede (
    id_imagen_sede   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta_imagen_sede VARCHAR(255) NOT NULL,
    id_sede          INTEGER NOT NULL REFERENCES sede(id_sede)
);

CREATE TABLE habitacion (
    id_habitacion      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero             INTEGER NOT NULL,
    tipo               VARCHAR(20) NOT NULL,
    estado             VARCHAR(20) NOT NULL DEFAULT 'Disponible',
    descripcion        VARCHAR(200) NOT NULL,
    precio_noche       NUMERIC(10,2) NOT NULL,
    capacidad_personas INTEGER NOT NULL,
    id_sede            INTEGER NOT NULL REFERENCES sede(id_sede),
    imagen             VARCHAR(200),
    CONSTRAINT numero_uq UNIQUE (numero)
);

CREATE TABLE imagen_habitacion (
    id_imagen_habitacion   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta_imagen_habitacion VARCHAR(255) NOT NULL,
    id_habitacion          INTEGER NOT NULL REFERENCES habitacion(id_habitacion)
);

CREATE TABLE reserva (
    id_reserva        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio      DATE NOT NULL,
    fecha_fin         DATE NOT NULL,
    fecha_reserva     DATE NOT NULL,
    total_noches      INTEGER NOT NULL,
    precio_total      NUMERIC(10,2) NOT NULL,
    estado            VARCHAR(20) NOT NULL,
    estado_pago       VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    cantidad_personas INTEGER NOT NULL,
    id_habitacion     INTEGER NOT NULL REFERENCES habitacion(id_habitacion),
    id_cliente        INTEGER NOT NULL REFERENCES cliente(id_cliente)
);

CREATE TABLE admin_sede (
    id_admin_sede INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_admin      INTEGER NOT NULL REFERENCES administrador(id_administrador),
    id_sede       INTEGER NOT NULL REFERENCES sede(id_sede)
);

